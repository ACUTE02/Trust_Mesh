"""Unified graph-engine leaderboard: Phase 1/1B/1C (artifacts/graph/results.json) + Phase 1D
(artifacts/graph/results_phase1d.json). Every row is temporal-split test PR-AUC (train steps 1-30,
test 36-49, labeled nodes only). The random-split GraphSAGE number is excluded on purpose -- it uses a
different split.

Usage:
  python scripts/build_graph_leaderboard.py                # print + write docs/graph_leaderboard.md
  python scripts/build_graph_leaderboard.py --merge        # also copy Phase 1D into results.json["phase1d"]
  python scripts/build_graph_leaderboard.py --phase1d PATH --out PATH   (custom inputs/outputs)
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def phase1_rows(r):
    c = r.get("phase1c", {})
    rob = r.get("robustness_check", {})
    rows = [
        ("XGBoost, raw features", "xgboost", "1", "25-trial Optuna", r["pr_auc_baseline_xgboost_tier1_temporal"], None),
        ("XGBoost, raw + Tier-2 graph features", "xgboost", "1B", "25-trial Optuna",
         r["pr_auc_baseline_xgboost_tier1_tier2_temporal"],
         (rob["mean"], rob["std"]) if rob.get("best_model") == "xgboost_tier1_tier2" else None),
        ("GraphSAGE, defaults", "graphsage", "1", "defaults, 40 epochs", r["pr_auc_gnn_graphsage_default_temporal"], None),
        ("GraphSAGE, tuned", "graphsage", "1B", "15-trial Optuna", r["pr_auc_gnn_graphsage_tuned_temporal"], None),
        ("GAT, defaults", "gat", "1B", "defaults, 40 epochs", r["pr_auc_gat_temporal"], None),
    ]
    if "wider_search_graphsage" in c:
        rows.append(("GraphSAGE, wide search", "graphsage", "1C",
                     f"{c['wider_search_graphsage']['n_trials']}-trial Optuna", c["wider_search_graphsage"]["pr_auc_temporal"], None))
    if "wider_search_gat" in c:
        rows.append(("GAT, tuned", "gat", "1C", f"{c['wider_search_gat']['n_trials']}-trial Optuna",
                     c["wider_search_gat"]["pr_auc_temporal"], None))
    if "gin" in c:
        rows.append(("GIN, defaults", "gin", "1C", "defaults, 40 epochs", c["gin"]["pr_auc_temporal"], None))
    return rows


PHASE1D_LABELS = {
    "xgboost_tier1": "XGBoost, raw features (1D refit)",
    "xgboost_tier12": "XGBoost, raw + Tier-2 graph features (1D refit)",
    "graphsage_wide_search": "GraphSAGE, wide search (1D refit)",
    "graphsage_expanded_search": "GraphSAGE, expanded search (best GNN overall)",
    "rgcn_single": "RGCN, untyped control (both directions)",
    "rgcn_direction": "RGCN, payment-direction relations",
    "rgcn_direction_hub": "RGCN, direction x hub relations",
    "care_gnn": "CARE-GNN (simplified, see design_decisions.md)",
}


def phase1d_rows(d):
    rob = d.get("robustness_best_gnn", {})
    rows = []
    for name, m in d.get("models", {}).items():
        label = PHASE1D_LABELS.get(name, name.replace("_", " "))
        seeds = (rob["mean"], rob["std"]) if rob.get("model") == name else None
        rows.append((label, m["family"], "1D", m["protocol"], m["pr_auc_test"], seeds))
    return rows


def render(rows, phase1d):
    rows = sorted(rows, key=lambda row: row[4], reverse=True)
    lines = [
        "# Graph Engine Leaderboard",
        "",
        "Elliptic, temporal split (train time steps 1-30, validation 31-35, test 36-49, labeled nodes only), "
        "class-weighted training, **test PR-AUC**. Generated by `scripts/build_graph_leaderboard.py` from "
        "`artifacts/graph/results.json` and `artifacts/graph/results_phase1d.json` -- do not edit by hand.",
        "",
        "| # | Model | Family | Phase | Protocol | Test PR-AUC | 3-seed mean ± std |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, (label, family, phase, protocol, score, seeds) in enumerate(rows, 1):
        seed_txt = f"{seeds[0]:.4f} ± {seeds[1]:.4f}" if seeds else ""
        lines.append(f"| {i} | {label} | {family} | {phase} | {protocol} | {score:.4f} | {seed_txt} |")
    if phase1d:
        repro = phase1d.get("reproduction", {})
        checks = ", ".join(f"{k}: {'OK' if v.get('match') else 'MISMATCH' if v.get('match') is False else 'skipped'}"
                           for k, v in repro.items())
        lines += ["", f"Phase 1D reproduction checks against notebook 01: {checks or 'not recorded'}."]
        if phase1d.get("smoke_test"):
            lines += ["", "**WARNING: the Phase 1D file is a synthetic smoke-test run. These rows are not real results.**"]
    lines += ["", "Rows marked \"1D refit\" re-fit an earlier model from its stored best hyperparameters to check that "
              "notebook 02 reproduces notebook 01's setup; the original Phase 1/1B/1C rows are kept as-is."]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=ROOT / "artifacts/graph/results.json", type=Path)
    ap.add_argument("--phase1d", default=ROOT / "artifacts/graph/results_phase1d.json", type=Path)
    ap.add_argument("--out", default=ROOT / "docs/graph_leaderboard.md", type=Path)
    ap.add_argument("--merge", action="store_true", help="copy Phase 1D results into results.json['phase1d']")
    args = ap.parse_args()

    results = json.loads(args.results.read_text(encoding="utf-8"))
    phase1d = json.loads(args.phase1d.read_text(encoding="utf-8")) if args.phase1d.exists() else None
    rows = phase1_rows(results) + (phase1d_rows(phase1d) if phase1d else [])
    text = render(rows, phase1d)
    print(text)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")

    if args.merge:
        if phase1d is None:
            raise SystemExit(f"--merge needs {args.phase1d}")
        if phase1d.get("smoke_test"):
            raise SystemExit("refusing to merge a smoke-test results file into results.json")
        results["phase1d"] = phase1d
        args.results.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
        print(f"merged Phase 1D into {args.results}")


if __name__ == "__main__":
    main()
