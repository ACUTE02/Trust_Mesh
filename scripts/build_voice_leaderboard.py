"""Voice-engine leaderboard: Phase 2 (artifacts/voice/results.json) + Phase 2B
(artifacts/voice/results_phase2b.json) -> docs/voice_leaderboard.md.

One table: model, features, split, seeds, EER (mean +/- std over seeds), 95% bootstrap CI, and the test
class counts next to every number. Phase 2 and Phase 2B rows use different test sets (Phase 2B has
~10x more bonafide clips), so they are listed together but must not be read as a like-for-like race.

Usage:
  python scripts/build_voice_leaderboard.py
  python scripts/build_voice_leaderboard.py --phase2b PATH --out PATH
"""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SPLIT_LABELS = {"P1": "speaker-disjoint, shared attacks", "P2": "speaker- and attack-disjoint"}
GROUP_LABELS = {
    "A_lcnn_trimmed": "A: LCNN, trimmed LFCC (headline)",
    "B_lcnn_trimmed_aug": "B: A + augmentation",
    "C_ssl_frozen": "C: frozen XLS-R + layer-weighted head",
    "U_lcnn_untrimmed_SHORTCUT": "LCNN, untrimmed -- SHORTCUT, not a result",
    "S_zeros_fixed": "Silence ablation: fixed-length zeros",
    "S_noise_fixed": "Silence ablation: fixed-length noise",
    "S_zeros_original_duration": "Silence ablation: zeros at original length",
    "S_silence_only": "Silence ablation: 0.2 s of silence only",
}


def fmt(x, digits=4):
    return "" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{digits}f}"


def phase2_rows(results):
    rows = []
    for name, m in results.get("models", {}).items():
        c = m["per_class_at_eer_threshold"]
        split = "speaker-disjoint, shared attacks" if m["split"] == "speaker_disjoint" else "random clip split"
        label = "LCNN, untrimmed -- SHORTCUT, not a result" if m["features"] == "untrimmed" else f"LCNN, {m['features']}"
        rows.append({"phase": "2", "model": label, "features": m["features"], "split": split, "seeds": "1",
                     "eer": fmt(m["eer"]), "ci": "not computed", "test": f"{c['n_bonafide']} / {c['n_spoof']}"})
    return rows


def phase2b_rows(results):
    rows = []
    for row in results.get("leaderboard", []):
        base = row["group"].removesuffix("_P2")
        eer = fmt(row["eer_mean"]) + (f" ± {fmt(row['eer_std'])}" if row.get("eer_std") is not None else "")
        rows.append({"phase": "2B", "model": GROUP_LABELS.get(base, base), "features": row["features"],
                     "split": SPLIT_LABELS.get(row["split"], row["split"]), "seeds": str(len(row["seeds"])),
                     "eer": eer, "ci": f"[{fmt(row['ci_first_seed'][0])}, {fmt(row['ci_first_seed'][1])}]",
                     "test": f"{row['test_counts']['bonafide']} / {row['test_counts']['spoof']}"})
    return rows


def render(rows, phase2b):
    lines = [
        "# Voice Engine Leaderboard",
        "",
        "ASVspoof 2019 LA **evaluation partition only** (not the official train/eval protocol -- no comparison "
        "with published ASVspoof numbers is valid). EER on each model's held-out test split; lower is better. "
        "Generated by `scripts/build_voice_leaderboard.py` -- do not edit by hand.",
        "",
        "| Phase | Model | Features | Split | Seeds | Test EER (mean ± std) | 95% CI (first seed) | Test bonafide / spoof |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['phase']} | {r['model']} | {r['features']} | {r['split']} | {r['seeds']} | {r['eer']} | "
                     f"{r['ci']} | {r['test']} |")
    lines += ["",
              "- Phase 2 used a 6000-clip streamed subset (619 bonafide); Phase 2B keeps every bonafide clip. Their "
              "test sets differ, so compare within a phase, not across.",
              "- Untrimmed rows exploit the ASVspoof silence artifact. They are listed only to show the size of the "
              "shortcut."]
    if phase2b:
        data = phase2b.get("data", {}).get("loaded", {})
        if data:
            lines.append(f"- Phase 2B data actually loaded: {data.get('clips')} clips ({data.get('bonafide')} bonafide / "
                         f"{data.get('spoof')} spoof, {data.get('speakers')} speakers).")
        held = phase2b.get("splits", {}).get("held_out_attacks")
        if held:
            lines.append(f"- Attack-disjoint split holds out {', '.join(held)} (one seeded draw).")
        not_run = phase2b.get("not_run") or {}
        for step, why in not_run.items():
            lines.append(f"- Not run: `{step}` -- {why}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase2", default=ROOT / "artifacts/voice/results.json", type=Path)
    ap.add_argument("--phase2b", default=ROOT / "artifacts/voice/results_phase2b.json", type=Path)
    ap.add_argument("--out", default=ROOT / "docs/voice_leaderboard.md", type=Path)
    ap.add_argument("--allow-smoke", action="store_true", help="render a smoke-test file (for testing the script only)")
    args = ap.parse_args()

    phase2 = json.loads(args.phase2.read_text(encoding="utf-8")) if args.phase2.exists() else {}
    phase2b = json.loads(args.phase2b.read_text(encoding="utf-8")) if args.phase2b.exists() else None
    for name, res in (("Phase 2", phase2), ("Phase 2B", phase2b)):
        if res and res.get("smoke_test") and not args.allow_smoke:
            raise SystemExit(f"refusing to build the leaderboard from a smoke-test {name} results file")
    rows = phase2_rows(phase2) + (phase2b_rows(phase2b) if phase2b else [])
    text = render(rows, phase2b)
    if phase2b and phase2b.get("smoke_test"):
        text = "**SMOKE-TEST OUTPUT -- synthetic data, numbers are meaningless.**\n\n" + text
    args.out.write_text(text, encoding="utf-8")
    print(text)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
