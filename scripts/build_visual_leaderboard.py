"""Visual-engine leaderboard: artifacts/visual/results_v1.json -> docs/visual_leaderboard.md.

One table per leave-one-family-out fold (rows = models, columns = test suites), then the folds side
by side, then the old-only ablation. Every cell is ROC-AUC with its 95% bootstrap CI, or "not yet
run". With no results file the template is written with every cell "not yet run".

Only aggregate numbers are read and written -- nothing per image.

Usage:
  python scripts/build_visual_leaderboard.py
  python scripts/build_visual_leaderboard.py --results PATH --out PATH
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOT_RUN = "not yet run"
MODELS = ["shortcut baseline (file properties after the shared pipeline)", "V1 logistic regression", "V1 MLP"]
SUITES = ["T1 known generators", "T3 unseen family", "T4 known, JPEG 90", "T4 known, JPEG 70", "T4 known, JPEG 50",
          "T4 unseen, JPEG 90", "T4 unseen, JPEG 70", "T4 unseen, JPEG 50"]
DEFERRED = {"T2 sibling generator": "not run (run only if the real metadata has a clean sibling pair)",
            "T5 screenshots": NOT_RUN, "T6 resize": NOT_RUN, "T7 crop": NOT_RUN, "T8 AI-edited pairs": NOT_RUN,
            "T9 real-world (Deepfake-Eval-2024)": NOT_RUN + " (once, after the V1 head is frozen, if access is granted)"}


def grid_table(grid):
    suites = list(next(iter(grid.values())).keys())
    lines = ["| Model | " + " | ".join(suites) + " |", "|---|" + "---|" * len(suites)]
    for model, cells in grid.items():
        lines.append(f"| {model} | " + " | ".join(str(cells.get(s, NOT_RUN)) for s in suites) + " |")
    return lines


def render(results):
    report = (results or {}).get("report") or {}
    folds = report.get("folds") or {"(folds not built yet)": {m: {s: NOT_RUN for s in SUITES} for m in MODELS}}
    lines = [
        "# Visual Engine Leaderboard (Version 1)",
        "",
        "Frozen CLIP ViT-L/14 embeddings + a small head. **Fake is the positive class.** Every cell is ROC-AUC with a 95% "
        'stratified bootstrap CI (1,000 resamples, first seed), or "not yet run". Generated by '
        "`scripts/build_visual_leaderboard.py` -- do not edit by hand.",
        "",
        "Each fold holds one generator family out of training entirely (leave-one-family-out). \"T1 known\" is that "
        "fold's test on generators it trained on; \"T3 unseen\" is its test on the held-out family. Folds share training "
        "data, so they are shown one by one and never pooled into a single CI.",
        "",
    ]
    for fold, grid in folds.items():
        lines += [f"## Held out: {fold}", ""] + grid_table(grid) + [""]
    lines += ["## Old-only ablation", "",
              "Trained on real images plus the old generator families only, scored on each modern family's unseen test "
              "(the same images its fold uses). An ablation, not a model to deploy.", ""]
    old_only = report.get("old_only_ablation", NOT_RUN)
    if isinstance(old_only, dict) and old_only:
        lines += ["| Modern family (unseen test) | Old-only ROC-AUC |", "|---|---|"]
        lines += [f"| {family} | {value} |" for family, value in old_only.items()]
    else:
        lines.append(NOT_RUN)
    lines += ["", "## Suites not part of Version 1", ""]
    lines += [f"- {name}: {status}" for name, status in (report.get("deferred_suites") or DEFERRED).items()]
    final = (results or {}).get("final_model") or {}
    lines += ["", "## Final model", "",
              final.get("what_it_cannot_claim", NOT_RUN + ". The final head is retrained on every family after evaluation; "
                        "it will have no unseen-generator test of its own, and the folds above will be its estimate, not a measurement.")]
    closing = (results or {}).get("closing_paragraph")
    if closing:
        lines += ["", "## This run, in words", "", closing]
    not_run = (results or {}).get("not_run") or {}
    if not_run:
        lines += ["", "## Not run in this results file", ""] + [f"- `{step}`: {why}" for step, why in not_run.items()]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=ROOT / "artifacts/visual/results_v1.json", type=Path)
    ap.add_argument("--out", default=ROOT / "docs/visual_leaderboard.md", type=Path)
    ap.add_argument("--allow-smoke", action="store_true", help="render a smoke-test file (for testing the script only)")
    args = ap.parse_args()
    results = json.loads(args.results.read_text(encoding="utf-8")) if args.results.exists() else None
    if results and results.get("smoke_test") and not args.allow_smoke:
        raise SystemExit("refusing to build the leaderboard from a smoke-test results file")
    text = render(results)
    if results and results.get("smoke_test"):
        text = "**SMOKE-TEST OUTPUT -- synthetic data, numbers are meaningless.**\n\n" + text
    args.out.write_text(text, encoding="utf-8")
    print(text)
    print(f"wrote {args.out}" + ("" if results else " (no results file yet: every cell says 'not yet run')"))


if __name__ == "__main__":
    main()
